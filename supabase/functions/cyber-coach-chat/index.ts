interface Message {
  role: 'user' | 'assistant' | 'system';
  content: string;
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages, type = 'chat' } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get('LOVABLE_API_KEY');

    if (!LOVABLE_API_KEY) {
      throw new Error('LOVABLE_API_KEY is not configured');
    }

    // Build conversation with RAG context
    const conversationMessages: Message[] = [
      { 
        role: 'system', 
        content: `${SYSTEM_PROMPT}\n\n## Knowledge Base\n${CYBER_KNOWLEDGE_BASE}` 
      },
      ...messages
    ];

    // Different prompts for different interaction types
    if (type === 'pathway-preview') {
      conversationMessages[0].content += `\n\n## Special Mode: Pathway Preview
The user has just shared their background. Generate a personalized 3-minute "Pathway Preview" that:
1. Identifies their 2-3 best-fit cyber roles based on their background
2. Explains why their experience transfers well
3. Gives them their "fastest proof" - one thing they can build/do this weekend
4. Provides a low-risk 3-6 month plan that doesn't require leaving their job

Make this feel like a supportive, personalized career coaching session.`;
    }

    if (type === 'dejargonise') {
      conversationMessages[0].content += `\n\n## Special Mode: De-Jargoniser
The user is asking about a technical term. Explain it:
1. In one plain English sentence
2. With a relatable real-world analogy
3. Why it matters for their career journey

Keep it simple, warm, and encouraging.`;
    }

    if (type === 'simulation') {
      conversationMessages[0].content += `\n\n## Special Mode: Audio Micro-Simulation
You're running a brief choose-your-own-adventure scenario. Set the scene:
1. Give them a realistic cyber scenario they might face in a role
2. Present 2-3 choices
3. Respond to their choice with feedback and consequences
4. Help them learn by doing

Make it feel real but safe - this is practice, not a test.`;
    }

    const response = await fetch('https://ai.gateway.lovable.dev/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${LOVABLE_API_KEY}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        model: 'google/gemini-3-flash-preview',
        messages: conversationMessages,
        stream: true,
      }),
    });

    if (!response.ok) {
      const errorText = await response.text();
      console.error('AI Gateway error:', response.status, errorText);
      
      if (response.status === 429) {
        return new Response(
          JSON.stringify({ error: 'Rate limit exceeded. Please try again in a moment.' }),
          { status: 429, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
        );
      }
      if (response.status === 402) {
        return new Response(
          JSON.stringify({ error: 'Usage limit reached. Please add credits to continue.' }),
          { status: 402, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
        );
      }
      
      throw new Error(`AI gateway error: ${response.status}`);
    }

    // Stream the response back
    return new Response(response.body, {
      headers: { ...corsHeaders, 'Content-Type': 'text/event-stream' },
    });

  } catch (error) {
    console.error('Cyber coach error:', error);
    return new Response(
      JSON.stringify({ 
        error: error instanceof Error ? error.message : 'An unexpected error occurred' 
      }),
      { status: 500, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    );
  }
});
